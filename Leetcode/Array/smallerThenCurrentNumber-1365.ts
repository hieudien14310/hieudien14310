function smallerNumbersThanCurrent(nums: number[]): number[] {
    const result: number[] = [];
    for (let i = 0; i < nums.length; i++){
        const fake = [...nums];
        fake.splice(i, 1);
        let count = 0;
        for (let j = 0; j < fake.length; j++) {
            if(nums[i] > fake[j]) count++;
        }
        result.push(count);
    }
    return result;
};
